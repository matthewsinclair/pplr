// fold-table: writes src/fold_table.rs, Foundation's case- and
// diacritic-insensitive fold for every Latin scalar where it differs from
// Unicode lowercasing (ST0001 WP04). The legacy engine folded with Foundation,
// so the port carries its answers rather than a hand-made accent list.
//
//   swiftc -o /tmp/fold-table tools/fold-table.swift && /tmp/fold-table > src/fold_table.rs

import Foundation

var rows: [String] = []
for range: ClosedRange<UInt32> in [0x00C0...0x024F, 0x1E00...0x1EFF] {
  for value in range {
    guard let scalar = Unicode.Scalar(value) else { continue }
    let s = String(Character(scalar))
    let folded = s.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
    if folded == s.lowercased() { continue }
    let text = folded.unicodeScalars
      .map { $0.isASCII ? String(Character($0)) : String(format: "\\u{%X}", $0.value) }.joined()
    rows.append(String(format: "  ('\\u{%X}', \"%@\"),", value, text))
  }
}
print("""
//! Generated by tools/fold-table.swift: do not edit. Foundation's case- and
//! diacritic-insensitive fold of each Latin scalar whose fold is not its
//! lowercase, sorted by scalar.

pub(crate) const FOLD: &[(char, &str)] = &[
\(rows.joined(separator: "\n"))
];
""")
