// fold-table: writes src/fold_table.rs, two Foundation answers for every
// Latin scalar (ST0001 WP04, WP10). FOLD is its case- and
// diacritic-insensitive fold where that differs from Unicode lowercasing,
// which the legacy engine compared names by; DECOMPOSE is its canonical
// decomposition, the form Foundation gave the file names it wrote. The port
// carries Foundation's answers rather than a hand-made accent list.
//
//   swiftc -o /tmp/fold-table tools/fold-table.swift && /tmp/fold-table > src/fold_table.rs

import Foundation

func literal(_ s: String) -> String {
  s.unicodeScalars
    .map { $0.isASCII ? String(Character($0)) : String(format: "\\u{%X}", $0.value) }.joined()
}

var folds: [String] = []
var decompositions: [String] = []
for range: ClosedRange<UInt32> in [0x00C0...0x024F, 0x1E00...0x1EFF] {
  for value in range {
    guard let scalar = Unicode.Scalar(value) else { continue }
    let s = String(Character(scalar))
    let folded = s.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
    if folded != s.lowercased() {
      folds.append(String(format: "  ('\\u{%X}', \"%@\"),", value, literal(folded)))
    }
    let decomposed = s.decomposedStringWithCanonicalMapping
    if decomposed.unicodeScalars.count > 1 {
      decompositions.append(String(format: "  ('\\u{%X}', \"%@\"),", value, literal(decomposed)))
    }
  }
}
print("""
//! Generated by tools/fold-table.swift: do not edit. Two Foundation answers
//! for Latin scalars, each sorted by scalar: FOLD, the case- and
//! diacritic-insensitive fold of each whose fold is not its lowercase; and
//! DECOMPOSE, the canonical decomposition of each that has one.

pub(crate) const FOLD: &[(char, &str)] = &[
\(folds.joined(separator: "\n"))
];

pub(crate) const DECOMPOSE: &[(char, &str)] = &[
\(decompositions.joined(separator: "\n"))
];
""")
